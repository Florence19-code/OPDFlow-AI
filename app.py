
import streamlit as st
import pandas as pd
import joblib

# Load the saved model and configuration
model = joblib.load("OPDFlow_AI_Model.joblib")
config = joblib.load("OPDFlow_AI_Config.joblib")

# Configure the dashboard
st.set_page_config(
    page_title="OPDFlow AI",
    page_icon="🏥",
    layout="wide"
)

# Dashboard heading
st.title("🏥 OPDFlow AI")
st.subheader("OPD Waiting-Time Prediction and Congestion Management")

st.write(
    "Enter the outpatient department details below "
    "to predict the patient's expected waiting time."
)

# Patient input form
st.header("Patient Details")

col1, col2 = st.columns(2)

with col1:
    department = st.selectbox(
        "Select Department",
        [
            "General Medicine",
            "Cardiology",
            "Orthopaedics",
            "Paediatrics",
            "Dermatology",
            "ENT"
        ]
    )

    arrival_hour = st.slider(
        "Arrival Hour",
        min_value=8,
        max_value=19,
        value=11
    )

    day_of_week = st.selectbox(
        "Day of the Week",
        [
            "Monday", "Tuesday", "Wednesday",
            "Thursday", "Friday", "Saturday", "Sunday"
        ]
    )

    appointment_type = st.selectbox(
        "Appointment Type",
        ["Appointment", "Walk-in"]
    )

with col2:
    patients_waiting = st.number_input(
        "Number of Patients Waiting",
        min_value=0,
        max_value=100,
        value=10
    )

    doctors_available = st.number_input(
        "Number of Doctors Available",
        min_value=1,
        max_value=10,
        value=2
    )

    avg_consultation_time = st.number_input(
        "Average Consultation Time (minutes)",
        min_value=5,
        max_value=60,
        value=15
    )

# Automatically calculate additional model features
peak_hour = 1 if 9 <= arrival_hour <= 12 else 0
weekend = 1 if day_of_week in ["Saturday", "Sunday"] else 0

# Predict waiting time
if st.button("Predict Waiting Time"):

    input_data = pd.DataFrame([{
        "Arrival_Hour": arrival_hour,
        "Department": department,
        "Day_of_Week": day_of_week,
        "Appointment_Type": appointment_type,
        "Patients_Waiting": patients_waiting,
        "Doctors_Available": doctors_available,
        "Avg_Consultation_Time": avg_consultation_time,
        "Peak_Hour": peak_hour,
        "Weekend": weekend
    }])

    # Generate prediction
    predicted_waiting_time = model.predict(input_data)[0]

    # Classify congestion
    if predicted_waiting_time < 20:
        congestion = "Low"
        st.success("Low Congestion")

    elif predicted_waiting_time <= 45:
        congestion = "Moderate"
        st.warning("Moderate Congestion")

    else:
        congestion = "High"
        st.error("High Congestion")

    # Display results
    st.subheader("Prediction Results")

    st.metric(
        label="Predicted Waiting Time",
        value=f"{predicted_waiting_time:.1f} minutes"
    )

    st.write("**Congestion Level:**", congestion)

    st.info(
        "This prediction is generated by the OPDFlow AI "
        "Random Forest model."
    )

# Project limitation
st.caption(
    "Academic prototype using synthetic data. "
    "Predictions are illustrative and should not be used "
    "as a substitute for actual hospital queue information."
)
